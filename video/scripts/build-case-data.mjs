/**
 * Generates src/data/case.ts from the product's own output.
 *
 * Every figure that appears on screen in the video comes through here. Nothing is
 * retyped by hand — which is the same rule web/src/lib/content.ts states for itself:
 * "If a number is not in the repo, it does not belong in this file."
 *
 * Run: npm run data
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");

const read = (p) => JSON.parse(readFileSync(join(repo, p), "utf8"));

const report = read("artifacts/demo/deterministic-report.json");
const investigation = read("artifacts/hf-real-vm/llm-investigation.json");

/* Scene 4 needs the injection as the product classified it, not as prose. */
const policyAlert = report.policy_alerts[0];

/* The raw attacker line, pulled from the fixture rather than transcribed. */
const journal = readFileSync(
  join(repo, "eval/fixtures/hospital-demo/commands/journal.txt"),
  "utf8",
).split("\n");
const injectionLineNumber = journal.findIndex((l) => l.includes("SYSTEM INSTRUCTION")) + 1;
const injectionLine = journal[injectionLineNumber - 1];

if (!injectionLine) {
  throw new Error("Injection line not found in hospital-demo/commands/journal.txt");
}

/* The model's own acknowledgement of the injection — scene 4's closing receipt. */
const llm = investigation.llm_analysis;
const injectionFinding = (llm.findings ?? []).find((f) =>
  /prompt.?injection/i.test(f.description ?? ""),
);

const toolTrace = investigation.tool_trace ?? [];

/**
 * Scene 2's verification rows. Real paths, real hashes, straight out of the bundle's
 * own SHA256SUMS. The README notes the fixture "follows the same layout as the real VM
 * collector", which is why these paths stand in for the real-VM run on screen.
 */
const bundle = readFileSync(join(repo, "eval/fixtures/hospital-demo/SHA256SUMS"), "utf8")
  .split("\n")
  .filter(Boolean)
  .map((line) => {
    const [sha, path] = line.trim().split(/\s+/);
    return { path, sha: sha.slice(0, 12).toUpperCase() };
  });

const data = {
  caseId: report.case_id,
  bundle,
  timelineCount: report.timeline.length,
  attackSteps: report.attack_path.length,
  techniques: report.techniques.map((t) => ({
    id: t.technique_id,
    name: t.name,
    evidenceIds: t.evidence_ids,
  })),
  iocCount: report.iocs.length,
  iocs: report.iocs.map((i) => ({ type: i.type, value: i.value, evidenceIds: i.evidence_ids })),
  policyAlert: {
    type: policyAlert.type,
    decision: policyAlert.decision,
    evidenceId: policyAlert.evidence_ids[0],
  },
  injection: {
    line: injectionLine,
    sourcePath: "commands/journal.txt",
    lineNumber: injectionLineNumber,
    evidenceId: policyAlert.evidence_ids[0],
  },
  attackPath: report.attack_path.map((s) => ({
    time: s.timestamp,
    type: s.event_type,
    summary: s.summary,
    evidenceIds: s.evidence_ids,
  })),
  llmRun: {
    toolCalls: toolTrace.length,
    exfiltration: llm.exfiltration_assessment ?? null,
    confidence: llm.confidence ?? null,
    injectionFinding: injectionFinding
      ? { id: injectionFinding.id, description: injectionFinding.description }
      : null,
  },
};

const banner = `/* GENERATED by scripts/build-case-data.mjs — do not edit by hand.
 * Source: artifacts/demo/deterministic-report.json
 *         artifacts/hf-real-vm/llm-investigation.json
 *         eval/fixtures/hospital-demo/commands/journal.txt
 * Regenerate with: npm run data
 */\n\n`;

writeFileSync(
  join(here, "..", "src", "data", "case.ts"),
  `${banner}export const CASE = ${JSON.stringify(data, null, 2)} as const;\n`,
);

console.log(
  `case.ts written — ${data.attackSteps} attack steps, ${data.techniques.length} techniques, ` +
    `${data.iocCount} IOCs, injection at ${data.injection.sourcePath}:${data.injection.lineNumber}, ` +
    `${data.llmRun.toolCalls} model tool calls.`,
);
